"""Regenerate offline BCP47 lookup tables from pinned or refreshed IANA data."""
from __future__ import annotations

import argparse
import hashlib
import itertools
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / "tests/fixtures/language"
OUTPUT = ROOT / "src/metadata/language/registry.rs"
SOURCES = {
    "language-subtag-registry": "https://www.iana.org/assignments/language-subtag-registry/language-subtag-registry",
    "language-tag-extensions-registry": "https://www.iana.org/assignments/language-tag-extensions-registry/language-tag-extensions-registry",
}


def records(text: str) -> list[dict[str, list[str]]]:
    result = []
    for block in text.split("%%"):
        record: dict[str, list[str]] = {}
        last = None
        for line in block.splitlines():
            if line.startswith(" ") and last:
                record[last][-1] += " " + line.strip()
            elif ": " in line:
                last, value = line.split(": ", 1)
                record.setdefault(last, []).append(value)
        if record:
            result.append(record)
    return result


def expand(subtag: str) -> list[str]:
    if ".." not in subtag:
        return [subtag.lower()]
    start, end = subtag.lower().split("..")
    assert len(start) == len(end) and start.isalpha() and end.isalpha()
    # Registry ranges are tiny reserved private-use blocks. Iterate only the
    # differing suffix so refreshing cannot expand a huge Cartesian product.
    prefix = ""
    for a, b in zip(start, end):
        if a != b:
            break
        prefix += a
    return [value for suffix in itertools.product("abcdefghijklmnopqrstuvwxyz", repeat=len(start) - len(prefix))
            if start <= (value := prefix + "".join(suffix)) <= end]


def table(name: str, values: list[str]) -> list[str]:
    values = sorted(set(values))
    assert all(v.isascii() and v.isalnum() and 1 <= len(v) <= 8 for v in values)
    lines = [f"pub(super) const {name}: &[[u8; 8]] = concat!("]
    for offset in range(0, len(values), 12):
        lines.append('    "' + "".join(v.ljust(8) for v in values[offset:offset + 12]) + '",')
    return lines + [").as_bytes().as_chunks::<8>().0;", ""]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--refresh", action="store_true", help="download current IANA snapshots before regenerating")
    parser.add_argument("--check", action="store_true", help="fail if pinned snapshots generate different tables")
    args = parser.parse_args()
    if args.check and args.refresh:
        parser.error("--check and --refresh are mutually exclusive")
    FIXTURES.mkdir(parents=True, exist_ok=True)
    sources = {}
    for name, url in SOURCES.items():
        path = FIXTURES / name
        if args.refresh:
            data = urllib.request.urlopen(url, timeout=60).read()
            path.write_bytes(data)
        sources[name] = path.read_bytes()
    subtags = records(sources["language-subtag-registry"].decode("utf-8"))
    extensions = records(sources["language-tag-extensions-registry"].decode("utf-8"))
    out = ["// Generated by scripts/update_language_registry.py; do not edit.",
           "// IANA protocol-registry data is CC0: https://www.iana.org/help/licensing-terms"]
    for name, data in sources.items():
        out += [f"// {SOURCES[name]}", f"// SHA-256: {hashlib.sha256(data).hexdigest()}"]
    out += ["", f'pub(super) const DATE: &str = "{subtags[0]["File-Date"][0]}";', ""]
    for kind in ["language", "script", "region", "variant"]:
        values = [v for r in subtags if r.get("Type") == [kind] for v in expand(r["Subtag"][0])]
        out += table(kind.upper(), values)
    out += ["pub(super) const EXTLANG: &[([u8; 8], &str)] = &["]
    for record in sorted((r for r in subtags if r.get("Type") == ["extlang"]), key=lambda r: r["Subtag"][0]):
        assert len(record["Prefix"]) == 1
        key = record["Subtag"][0].lower().ljust(8)
        out.append(f'    (*b"{key}", "{record["Prefix"][0].lower()}"),')
    out += ["];", "", 'pub(super) const EXTENSIONS: &[u8] = b"' + "".join(sorted(r["Identifier"][0].lower() for r in extensions if "Identifier" in r)) + '";', ""]
    text = "\n".join(out)
    # rustfmt follows concat! with multiline method calls. Keep regeneration
    # deterministic without depending on a particular installed formatter.
    text = text.replace(").as_bytes().as_chunks::<8>().0;", ")\n.as_bytes()\n.as_chunks::<8>()\n.0;")
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit("IANA tables differ: regenerate with this script")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"IANA {subtags[0]['File-Date'][0]}: generated tables {len(text):,} source bytes")


if __name__ == "__main__":
    main()
